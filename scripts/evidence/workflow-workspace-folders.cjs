// Browser launch -> encrypted machine RPC -> real Codex workflow turns.
// This script only accepts an isolated Talos development environment.
const fs = require('node:fs');
const path = require('node:path');
const assert = require('node:assert/strict');
const { createHash, randomBytes, randomUUID } = require('node:crypto');
const { execFileSync } = require('node:child_process');
const { createRequire } = require('node:module');

const req = createRequire(path.join(process.cwd(), 'packages/talos-app/package.json'));
const nacl = req('tweetnacl');
const { WorkflowDefinitionSchema, workflowProjection } = req('@ahmadposten/talos-wire');
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright');

const evidence = path.join(process.cwd(), 'docs/evidence/workflow-workspace-folders');
const read = file => fs.readFileSync(file, 'utf8');
const git = (cwd, args) => execFileSync('git', ['-C', cwd, ...args], { encoding: 'utf8' });

function createFixtures() {
    const direct = fs.realpathSync(fs.mkdtempSync('/tmp/talos-workspace-folder-'));
    fs.writeFileSync(path.join(direct, 'ROOT.md'), 'Direct workspace root.\n');
    const nested = path.join(direct, 'service');
    fs.mkdirSync(nested);
    fs.writeFileSync(path.join(nested, 'README.md'), 'Nested repository.\n');
    git(nested, ['init', '-q']);
    git(nested, ['add', '.']);
    git(nested, ['-c', 'user.name=Talos E2E', '-c', 'user.email=e2e@example.invalid', 'commit', '-qm', 'Fixture']);

    const isolated = fs.realpathSync(fs.mkdtempSync('/tmp/talos-workspace-git-'));
    fs.writeFileSync(path.join(isolated, 'ROOT.md'), 'Isolated Git workspace.\n');
    git(isolated, ['init', '-q']);
    git(isolated, ['add', '.']);
    git(isolated, ['-c', 'user.name=Talos E2E', '-c', 'user.email=e2e@example.invalid', 'commit', '-qm', 'Fixture']);
    return { direct, nested, isolated };
}

function definition() {
    const slot = (name, assignment, permissionMode = 'read-only') => ({ assignment, agent: {
        id: randomUUID(), name, revision: 1, provider: 'codex', model: process.env.WORKFLOW_CODEX_MODEL || 'gpt-5.6-sol',
        effort: process.env.WORKFLOW_CODEX_EFFORT || 'low', permissionMode, description: '',
        instructions: 'Complete this tiny evidence fixture. Inspect the actual files and current working directory. Do not delegate. Return only the workflow decision JSON requested by Talos.', documents: [],
    } });
    const steps = [
        { id: randomUUID(), name: 'Plan', kind: 'plan', agents: [slot('Folder planner', 'Plan the two exact file writes. Do not write files.')], criteria: 'The plan preserves existing files and names both outputs.', checks: [] },
        { id: randomUUID(), name: 'Build', kind: 'execute', agents: [slot('Folder builder', 'At the current workspace root, create root-result.txt containing exactly root done and a newline. If service/ is present, create service/nested-result.txt containing exactly nested done and a newline. Preserve every existing file.', 'default')], criteria: 'The requested files exist at the current workspace root.', checks: [] },
        { id: randomUUID(), name: 'Review', kind: 'review', agents: [slot('Folder reviewer', 'Read the existing and generated files from the actual current workspace. Verify exact contents and do not write files.')], criteria: 'Existing files are preserved and generated bytes are exact.', checks: [] },
    ];
    return WorkflowDefinitionSchema.parse({
        id: randomUUID(), revision: 1, name: 'Workspace folder E2E', description: 'Direct folder and clean Git isolation control.',
        steps, ...workflowProjection(steps),
        criteria: 'root-result.txt is exactly root done newline. When service exists, service/nested-result.txt is exactly nested done newline. Existing fixture files remain unchanged.',
        checks: [{ name: 'Verify exact workspace', command: `python3 -c 'from pathlib import Path; p=Path.cwd(); assert (p/"root-result.txt").read_text()=="root done\\n"; assert (p/"ROOT.md").exists(); s=p/"service"; assert not s.exists() or (s/"nested-result.txt").read_text()=="nested done\\n"'` }],
        planningRounds: 2, reviewRounds: 2, turnMinutes: 3, maxTurns: 15, approvePlan: false, updatedAt: Date.now(),
    });
}

async function saveEncryptedDefinition(api, auth, workflow) {
    const secret = Buffer.from(auth.secret, 'base64');
    for (let attempt = 0; attempt < 5; attempt++) {
        const response = await fetch(api + '/v1/account/settings', { headers: { Authorization: 'Bearer ' + auth.token } });
        assert(response.ok, 'Could not load isolated account settings');
        const current = await response.json();
        let settings = {};
        if (current.settings) {
            const bytes = Buffer.from(current.settings, 'base64');
            const plain = nacl.secretbox.open(bytes.subarray(24), bytes.subarray(0, 24), secret);
            assert(plain, 'Could not decrypt isolated account settings');
            settings = JSON.parse(Buffer.from(plain).toString());
        }
        settings.workflowLibraryV3 = [...(settings.workflowLibraryV3 || []).filter(item => item.name !== workflow.name), workflow];
        settings.experiments = true;
        settings.expWorkflows = true;
        const nonce = randomBytes(24);
        const encrypted = Buffer.concat([nonce, Buffer.from(nacl.secretbox(Buffer.from(JSON.stringify(settings)), nonce, secret))]).toString('base64');
        const save = await fetch(api + '/v1/account/settings', {
            method: 'POST', headers: { Authorization: 'Bearer ' + auth.token, 'Content-Type': 'application/json' },
            body: JSON.stringify({ settings: encrypted, expectedVersion: current.settingsVersion }),
        });
        assert(save.ok, 'Could not save isolated account settings');
        if ((await save.json()).success) return;
        assert(attempt < 4, 'Concurrent settings changes prevented fixture save');
    }
}

async function selectProject(page, directory) {
    await page.getByRole('button', { name: /^Project:/ }).click();
    await page.getByRole('textbox', { name: 'Project directory', exact: true }).fill(directory);
    await page.getByRole('button', { name: 'Use this project', exact: true }).click();
    await page.getByRole('textbox', { name: 'Project directory', exact: true }).waitFor({ state: 'hidden' });
    await page.waitForTimeout(500);
}

async function captureReady(page, web, workflowId, source, label) {
    await page.goto(`${web}/workflows/run?workflowId=${workflowId}`);
    const task = page.getByRole('textbox', { name: 'Workflow task', exact: true });
    await task.waitFor({ timeout: 60000 });
    await task.fill('Create root-result.txt with exactly root done and a newline. If service exists, also create service/nested-result.txt with exactly nested done and a newline. Preserve existing files.');
    await selectProject(page, source);
    await page.getByRole('button', { name: 'Start workflow', exact: true }).waitFor();
    await page.screenshot({ path: path.join(evidence, `${label}-ready.png`) });
}

async function captureCompleted(page, web, machineId, runId, source, label, isolated) {
    await page.goto(`${web}/workflows/${runId}?machineId=${encodeURIComponent(machineId)}`);
    const success = page.getByText('Every required approval and check passed', { exact: true });
    await success.waitFor({ timeout: 60000 });
    await success.scrollIntoViewIfNeeded();
    await page.screenshot({ path: path.join(evidence, `${label}-complete-overview.png`) });
    await page.getByRole('button', { name: /^Verify exact workspace: Passed\./ }).waitFor();
    const show = page.getByText('Show details', { exact: true });
    await show.scrollIntoViewIfNeeded();
    await show.click();
    const title = page.getByText(isolated ? 'Worktree' : 'Directory', { exact: true });
    await title.scrollIntoViewIfNeeded();
    await page.getByText(source, { exact: true }).first().waitFor();
    if (isolated) {
        await page.getByText(/^Branch: talos\/workflow-/).waitFor();
        const metadata = page.getByText(/Base commit: [0-9a-f]+/);
        await metadata.waitFor();
        await metadata.scrollIntoViewIfNeeded();
    } else {
        assert.equal(await page.getByText(/^Branch:/).count(), 0);
        assert.equal(await page.getByText(/^Base commit:/).count(), 0);
        await page.getByText(/^Verified contents: [0-9a-f]+/).scrollIntoViewIfNeeded();
    }
    await page.setViewportSize({ width: 390, height: 1100 });
    await page.screenshot({ path: path.join(evidence, `${label}-workspace-details.png`) });
    await page.setViewportSize({ width: 390, height: 844 });
}

async function runWorkflow(page, web, workflow, source, label, isolated) {
    await captureReady(page, web, workflow.id, source, label);
    await page.getByRole('button', { name: 'Start workflow', exact: true }).click();
    await page.waitForURL(/\/workflows\/[0-9a-f-]{36}\?machineId=/, { timeout: 180000 });
    const url = new URL(page.url());
    const runId = url.pathname.split('/').pop();
    await page.getByText('Every required approval and check passed', { exact: true }).waitFor({ timeout: 15 * 60000 });
    await captureCompleted(page, web, url.searchParams.get('machineId'), runId, source, label, isolated);
    return runId;
}

function screenshotManifest() {
    const images = fs.readdirSync(evidence).filter(name => name.endsWith('.png')).sort().map(name => {
        const file = path.join(evidence, name);
        return { file: name, sha256: createHash('sha256').update(fs.readFileSync(file)).digest('hex'), bytes: fs.statSync(file).size };
    });
    fs.writeFileSync(path.join(evidence, 'manifest.json'), JSON.stringify({ capturedAt: new Date().toISOString(), images }, null, 2) + '\n');
}

async function main() {
    const envDir = process.env.WORKFLOW_E2E_ENV;
    assert(envDir?.includes('/environments/data/envs/'), 'Set WORKFLOW_E2E_ENV to an isolated Talos environment');
    const env = JSON.parse(read(path.join(envDir, 'environment.json')));
    const api = `http://localhost:${env.serverPort}`, web = `http://localhost:${env.expoPort}`;
    const auth = JSON.parse(read(path.join(envDir, 'cli/home/access.key')));
    assert(auth.token && auth.secret, 'Isolated environment is not authenticated');
    fs.mkdirSync(evidence, { recursive: true });
    const prior = process.env.WORKFLOW_CAPTURE_EXISTING ? JSON.parse(read(path.join(evidence, 'validation.json'))) : null;
    if (prior) {
        const machines = await fetch(api + '/v1/machines', { headers: { Authorization: 'Bearer ' + auth.token } });
        assert(machines.ok, 'Could not load isolated machines');
        const machine = (await machines.json())[0];
        assert(machine?.id, 'No isolated machine is registered');
        const browser = await chromium.launch({ channel: 'chrome', headless: true, timeout: 30000 });
        try {
            const context = await browser.newContext({ viewport: { width: 390, height: 844 } });
            await context.addInitScript(({ origin, credentials }) => {
                if (location.origin === origin) localStorage.setItem('auth_credentials', JSON.stringify(credentials));
            }, { origin: web, credentials: auth });
            const page = await context.newPage();
            await captureReady(page, web, prior.workflowId, prior.directSource, 'direct-folder');
            await captureCompleted(page, web, machine.id, prior.directRunId, prior.directSource, 'direct-folder', false);
            await captureReady(page, web, prior.workflowId, prior.isolatedSource, 'clean-git-control');
            await captureCompleted(page, web, machine.id, prior.isolatedRunId, prior.isolatedSource, 'clean-git-control', true);
            screenshotManifest();
            console.log(JSON.stringify({ captured: true, directRunId: prior.directRunId, isolatedRunId: prior.isolatedRunId }));
        } finally { await browser.close(); }
        return;
    }
    const fixtures = createFixtures();
    const workflow = definition();
    await saveEncryptedDefinition(api, auth, workflow);

    const browser = await chromium.launch({ channel: 'chrome', headless: true, timeout: 30000 });
    const results = { environment: env.name, workflowId: workflow.id, directSource: fixtures.direct, isolatedSource: fixtures.isolated };
    try {
        const context = await browser.newContext({ viewport: { width: 390, height: 844 } });
        await context.addInitScript(({ origin, credentials }) => {
            if (location.origin === origin) localStorage.setItem('auth_credentials', JSON.stringify(credentials));
        }, { origin: web, credentials: auth });
        const page = await context.newPage();

        results.directRunId = await runWorkflow(page, web, workflow, fixtures.direct, 'direct-folder', false);
        assert.equal(fs.existsSync(path.join(envDir, 'cli/home/workflow-worktrees', results.directRunId)), false);
        assert.equal(read(path.join(fixtures.direct, 'root-result.txt')), 'root done\n');
        assert.equal(read(path.join(fixtures.nested, 'nested-result.txt')), 'nested done\n');
        assert.equal(read(path.join(fixtures.direct, 'ROOT.md')), 'Direct workspace root.\n');
        assert.equal(read(path.join(fixtures.nested, 'README.md')), 'Nested repository.\n');
        assert.equal(fs.existsSync(path.join(fixtures.direct, '.git')), false);
        assert.match(git(fixtures.nested, ['status', '--porcelain']), /nested-result\.txt/);

        results.isolatedRunId = await runWorkflow(page, web, workflow, fixtures.isolated, 'clean-git-control', true);
        const isolatedWorktree = path.join(envDir, 'cli/home/workflow-worktrees', results.isolatedRunId);
        assert.equal(fs.existsSync(path.join(fixtures.isolated, 'root-result.txt')), false);
        assert.equal(git(fixtures.isolated, ['status', '--porcelain']), '');
        assert.equal(read(path.join(isolatedWorktree, 'root-result.txt')), 'root done\n');
        assert.equal(read(path.join(fixtures.isolated, 'ROOT.md')), 'Isolated Git workspace.\n');
        results.directExactCwd = true;
        results.nestedGitEdited = true;
        results.cleanGitSourceUnchanged = true;
        results.cleanGitWorktree = isolatedWorktree;
        results.realCodexTurns = true;
        fs.writeFileSync(path.join(evidence, 'validation.json'), JSON.stringify(results, null, 2) + '\n');
        screenshotManifest();
        console.log(JSON.stringify({ complete: true, directRunId: results.directRunId, isolatedRunId: results.isolatedRunId }));
    } finally {
        await browser.close();
    }
}

main().catch(error => { console.error(error.stack || error.message); process.exitCode = 1; });
